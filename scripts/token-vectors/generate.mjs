import { build } from "../../../identity/node_modules/esbuild/lib/main.js";
import { mkdtempSync, rmSync, writeFileSync } from "node:fs";
import { tmpdir } from "node:os";
import { join, dirname } from "node:path";
import { fileURLToPath, pathToFileURL } from "node:url";

const here = dirname(fileURLToPath(import.meta.url));
const identityTokens = join(here, "../../../identity/src/tokens.ts");
const sharedVerifier = join(here, "../../../lib/src/accessToken.ts");
const output = join(here, "../../test-vectors/midgar-token.json");

const NOW_MS = 1_800_000_000_000;
const KID = "mako-vector-key";
const encoder = new TextEncoder();

/**
 * Bundles identity's own signer so the vectors come from the code that mints production tokens.
 */
async function bundleAndLoad(entry) {
  const dir = mkdtempSync(join(tmpdir(), "mako-vectors-"));
  const outfile = join(dir, "bundle.mjs");
  try {
    await build({ entryPoints: [entry], bundle: true, format: "esm", platform: "node", outfile, logLevel: "error" });
    return await import(pathToFileURL(outfile).href);
  } finally {
    rmSync(dir, { recursive: true, force: true });
  }
}

/**
 * A throwaway P-256 key, loaded through identity's `loadSigningKey` exactly as the secret is in production.
 */
async function throwawayKey(signer, kid) {
  const pair = await crypto.subtle.generateKey({ name: "ECDSA", namedCurve: "P-256" }, true, ["sign", "verify"]);
  const jwk = await crypto.subtle.exportKey("jwk", pair.privateKey);
  return signer.loadSigningKey(JSON.stringify({ ...jwk, kid }));
}

function base64Url(bytes) {
  return Buffer.from(bytes).toString("base64url");
}

/**
 * Signs arbitrary claims with a key, for the tokens identity's signer would never mint.
 */
async function signRaw(key, header, claims) {
  const input = `${base64Url(encoder.encode(JSON.stringify(header)))}.${base64Url(encoder.encode(JSON.stringify(claims)))}`;
  const signature = await crypto.subtle.sign({ name: "ECDSA", hash: "SHA-256" }, key.privateKey, encoder.encode(input));
  return `${input}.${base64Url(new Uint8Array(signature))}`;
}

function claimsOf(token) {
  return JSON.parse(Buffer.from(token.split(".")[1], "base64url").toString());
}

const EXPECTED_REASONS = {
  attested: null,
  development: null,
  unverified: null,
  other_signer: "unknown_key",
  unknown_kid: "unknown_key",
  tampered_payload: "bad_signature",
  wrong_issuer: "invalid_claims",
  wrong_audience: "invalid_claims",
  wrong_tier: "invalid_claims",
  missing_tier: "invalid_claims",
  empty_subject: "invalid_claims",
  hs256: "malformed",
  no_kid: "malformed",
};

/**
 * Refuses to write vectors the shared verifier (the reference implementation) judges differently than listed.
 */
async function assertAgainstSharedVerifier(vectors, verifier) {
  for (const [name, token] of Object.entries(vectors.tokens)) {
    const result = await verifier.verifyAccessToken(token, vectors.jwks.keys, { now: vectors.iat + 10 });
    const reason = result.ok ? null : result.reason;
    if (reason !== EXPECTED_REASONS[name]) throw new Error(`${name}: expected ${EXPECTED_REASONS[name]}, the shared verifier says ${reason}`);
  }
  const expired = await verifier.verifyAccessToken(vectors.tokens.attested, vectors.jwks.keys, { now: vectors.exp });
  if (expired.ok || expired.reason !== "expired") throw new Error("the attested token should expire at exp");
}

const MIDGAR_ID = "0194F3A2-7B1C-4D2E-9A60-3C5E8F1B2D47";
const ATTESTED_KEY = "AAECAwQFBgcICQoLDA0ODxAREhMUFRYXGBkaGxwdHh8=";

const signer = await bundleAndLoad(identityTokens);
const verifier = await bundleAndLoad(sharedVerifier);
const key = await throwawayKey(signer, KID);
const stranger = await throwawayKey(signer, "mako-vector-stranger");

const attested = await signer.signAccessToken(key, { midgarId: MIDGAR_ID, appId: "dream-eater", attestation: "app_attest", keyId: ATTESTED_KEY }, NOW_MS);
const development = await signer.signAccessToken(key, { midgarId: MIDGAR_ID, appId: "pay-day", attestation: "development", keyId: ATTESTED_KEY }, NOW_MS);
const unverified = await signer.signAccessToken(key, { midgarId: MIDGAR_ID, appId: "pixiepocket", attestation: "unverified", keyId: null }, NOW_MS);
const base = claimsOf(attested);
const header = { alg: "ES256", typ: "JWT", kid: KID };

const [h, p, s] = attested.split(".");
const forgedPayload = base64Url(encoder.encode(JSON.stringify({ ...base, sub: MIDGAR_ID.replace("0194", "0195") })));

const vectors = {
  note: "Generated by scripts/token-vectors/generate.mjs with services/identity's signAccessToken and a throwaway key whose private half is discarded.",
  now_ms: NOW_MS,
  iat: base.iat,
  exp: base.exp,
  midgar_id: MIDGAR_ID,
  jwks: { keys: [key.publicJwk] },
  other_jwks: { keys: [stranger.publicJwk] },
  tokens: {
    attested,
    development,
    unverified,
    other_signer: await signer.signAccessToken(stranger, { midgarId: MIDGAR_ID, appId: "dream-eater", attestation: "app_attest", keyId: ATTESTED_KEY }, NOW_MS),
    unknown_kid: await signRaw(stranger, { ...header, kid: "mako-vector-stranger" }, base),
    tampered_payload: `${h}.${forgedPayload}.${s}`,
    wrong_issuer: await signRaw(key, header, { ...base, iss: "someone-else" }),
    wrong_audience: await signRaw(key, header, { ...base, aud: "other" }),
    wrong_tier: await signRaw(key, header, { ...base, att: "root" }),
    missing_tier: await signRaw(key, header, Object.fromEntries(Object.entries(base).filter(([name]) => name !== "att"))),
    empty_subject: await signRaw(key, header, { ...base, sub: "" }),
    hs256: await signRaw(key, { ...header, alg: "HS256" }, base),
    no_kid: await signRaw(key, { alg: "ES256", typ: "JWT" }, base),
  },
};

await assertAgainstSharedVerifier(vectors, verifier);
writeFileSync(output, `${JSON.stringify(vectors, null, 2)}\n`);
console.log(`wrote ${output}`);
